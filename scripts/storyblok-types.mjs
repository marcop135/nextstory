/**
 * Generate TypeScript block types from storyblok/components.json.
 *
 *   node scripts/storyblok-types.mjs           write src/types/storyblok.generated.ts
 *   node scripts/storyblok-types.mjs --check   exit 1 if the file is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const SOURCE = "storyblok/components.json";
const TARGET = "src/types/storyblok.generated.ts";
const CHECK = process.argv.includes("--check");

const components = JSON.parse(readFileSync(SOURCE, "utf8"));

const pascal = (name) =>
  name.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase()) + "Blok";

function fieldType(field) {
  switch (field.type) {
    case "text":
    case "textarea":
      return "string";
    case "options":
      return "string[]";
    case "boolean":
      return "boolean";
    case "table":
      return "{ fieldtype: 'table'; thead: { _uid: string; value: string }[]; tbody: { _uid: string; body: { _uid: string; value: string }[] }[] }";
    case "richtext":
      return "StoryblokRichTextInput";
    case "asset":
      return "{ filename: string; alt?: string | null; copyright?: string | null; source?: string | null }";
    case "bloks": {
      const allowed = field.component_whitelist ?? [];
      if (allowed.length === 0) return "SbBlokData[]";
      if (allowed.length === 1) return `${pascal(allowed[0])}[]`;
      return `(${allowed.map(pascal).join(" | ")})[]`;
    }
    default:
      throw new Error(`Unsupported field type "${field.type}" in ${SOURCE}`);
  }
}

const blocks = components.map((component) => {
  const fields = Object.entries(component.schema)
    .sort(([, a], [, b]) => a.pos - b.pos)
    .map(([key, field]) => {
      const optional = field.required ? "" : "?";
      return `  ${key}${optional}: ${fieldType(field)};`;
    });
  return [
    `export type ${pascal(component.name)} = SbBlokData & {`,
    `  component: "${component.name}";`,
    ...fields,
    "};",
  ].join("\n");
});

const output = `// Generated by scripts/storyblok-types.mjs from ${SOURCE}. Do not edit.
import type { SbBlokData, StoryblokRichTextInput } from "@storyblok/react";

${blocks.join("\n\n")}

export type StoryblokComponentName =
${components.map((c) => `  | "${c.name}"`).join("\n")};
`;

if (CHECK) {
  if (!existsSync(TARGET) || readFileSync(TARGET, "utf8") !== output) {
    console.error(`${TARGET} is stale: run npm run storyblok:types and commit.`);
    process.exit(1);
  }
  console.log(`${TARGET} is current`);
} else {
  writeFileSync(TARGET, output);
  console.log(`wrote ${TARGET} (${components.length} components)`);
}
